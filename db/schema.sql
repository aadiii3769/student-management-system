-- Drop table if already exists (safe re-run)
BEGIN
    EXECUTE IMMEDIATE 'DROP TABLE STUDENTS CASCADE CONSTRAINTS';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -942 THEN
            RAISE;
        END IF;
END;
/

-- Create standalone STUDENTS table
CREATE TABLE STUDENTS (
    STUDENT_ID    NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY,
    ROLL_NUMBER   VARCHAR2(20)   NOT NULL,
    FULL_NAME     VARCHAR2(100)  NOT NULL,
    EMAIL         VARCHAR2(100)  NOT NULL,
    PHONE         VARCHAR2(15)   NOT NULL,
    DEPARTMENT    VARCHAR2(80)   NOT NULL,
    YEAR          NUMBER(1)      NOT NULL,
    SECTION       VARCHAR2(5),
    GENDER        VARCHAR2(10),
    DATE_OF_BIRTH DATE,
    ADDRESS       VARCHAR2(250),
    CREATED_AT    TIMESTAMP      DEFAULT SYSTIMESTAMP NOT NULL,

    -- Constraints
    CONSTRAINT PK_STUDENTS_ID     PRIMARY KEY (STUDENT_ID),
    CONSTRAINT UQ_STUDENTS_ROLL   UNIQUE (ROLL_NUMBER),
    CONSTRAINT UQ_STUDENTS_EMAIL  UNIQUE (EMAIL),
    CONSTRAINT CHK_STUDENTS_YEAR  CHECK (YEAR BETWEEN 1 AND 5),
    CONSTRAINT CHK_STUDENTS_GENDER CHECK (GENDER IN ('Male', 'Female', 'Other'))
);

-- Comments for database documentation
COMMENT ON TABLE  STUDENTS               IS 'Central table for all student records in the SIMS application.';
COMMENT ON COLUMN STUDENTS.STUDENT_ID    IS 'Surrogate primary key auto-generated by Oracle IDENTITY.';
COMMENT ON COLUMN STUDENTS.ROLL_NUMBER   IS 'Unique institutional roll number (e.g., 24IT001).';
COMMENT ON COLUMN STUDENTS.FULL_NAME     IS 'Student legal full name.';
COMMENT ON COLUMN STUDENTS.EMAIL         IS 'Contact email address.';
COMMENT ON COLUMN STUDENTS.PHONE         IS '10-digit mobile contact number.';
COMMENT ON COLUMN STUDENTS.DEPARTMENT    IS 'Academic department / degree program.';
COMMENT ON COLUMN STUDENTS.YEAR          IS 'Academic year of study (1 to 4).';
COMMENT ON COLUMN STUDENTS.SECTION       IS 'Assigned class section (e.g. A, B, C).';
COMMENT ON COLUMN STUDENTS.GENDER        IS 'Gender: Male, Female, or Other.';
COMMENT ON COLUMN STUDENTS.DATE_OF_BIRTH IS 'Date of birth.';
COMMENT ON COLUMN STUDENTS.ADDRESS       IS 'Residential contact address.';
